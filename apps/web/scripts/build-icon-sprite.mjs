#!/usr/bin/env node
/**
 * Builds public/sprite/lucide.svg from the icon names listed in
 * src/app/shared/icons/icon-names.ts, using the SVGs of the pinned
 * `lucide-static` package. Each icon becomes a <symbol id="name">; stroke,
 * width and colour are set by the <svg> that references it (app-icon).
 *
 *   npm run icons -w @monkimoney/web
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const lucideDir = join(dirname(require.resolve('lucide-static/package.json')), 'icons')
const { version } = JSON.parse(readFileSync(require.resolve('lucide-static/package.json'), 'utf8'))

const namesSource = readFileSync(join(root, 'src/app/shared/icons/icon-names.ts'), 'utf8')
const listBody = /ICON_NAMES = \[([\s\S]*?)\] as const/.exec(namesSource)?.[1]
if (!listBody) {
  throw new Error('ICON_NAMES not found in icon-names.ts')
}
const names = [...listBody.matchAll(/'([a-z0-9-]+)'/g)].map((match) => match[1])

const symbols = names.map((name) => {
  const svg = readFileSync(join(lucideDir, `${name}.svg`), 'utf8')
  const inner = /<svg[^>]*>([\s\S]*?)<\/svg>/.exec(svg)?.[1]
  if (!inner) {
    throw new Error(`Could not read lucide icon "${name}"`)
  }
  const body = inner
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .join('')
  return `<symbol id="${name}" viewBox="0 0 24 24">${body}</symbol>`
})

const sprite = [
  `<!-- Generated by scripts/build-icon-sprite.mjs from lucide-static v${version} (ISC). Do not edit. -->`,
  '<svg xmlns="http://www.w3.org/2000/svg">',
  ...symbols,
  '</svg>',
  '',
].join('\n')

const outDir = join(root, 'public', 'sprite')
mkdirSync(outDir, { recursive: true })
writeFileSync(join(outDir, 'lucide.svg'), sprite)
console.log(`sprite/lucide.svg: ${names.length} icons`)
